"""World-model head: predict future touch and future vision from past frames only.

Added to the official codebase; nothing else in this tree changes. Design follows
docs/next_experiments.md of this project: frozen encoder, future-time queries, a latent readout of
the future visual target, and touch generated by a rectified flow over the 216 points of each hand.
The model is causal by construction, because future frames are never passed to it.
"""
from __future__ import annotations

import math

import torch
from torch import nn

NUM_POINTS = 216
FEATURE_DIM = 768
VISUAL_DIM = 1024
LOG_DISTANCE_MEAN = 2.5
LOG_DISTANCE_STD = 1.5
PROBABILITY_SHARPNESS = 6.0


def distance_to_target(distance_m: torch.Tensor) -> torch.Tensor:
    """Same target as the paper's Eq. 6, log(1 + 1000 d), then standardized for the flow."""
    return (torch.log1p(1000.0 * distance_m) - LOG_DISTANCE_MEAN) / LOG_DISTANCE_STD


def target_to_log_distance(value: torch.Tensor) -> torch.Tensor:
    return (value * LOG_DISTANCE_STD + LOG_DISTANCE_MEAN).clamp_min(0.0)


class _Block(nn.Module):
    def __init__(self, dim: int, heads: int):
        super().__init__()
        self.norm1 = nn.LayerNorm(dim, elementwise_affine=False)
        self.attn = nn.MultiheadAttention(dim, heads, batch_first=True)
        self.norm2 = nn.LayerNorm(dim, elementwise_affine=False)
        self.mlp = nn.Sequential(nn.Linear(dim, 4 * dim), nn.GELU(), nn.Linear(4 * dim, dim))
        self.film = nn.Linear(dim, 4 * dim)
        nn.init.zeros_(self.film.weight)
        nn.init.zeros_(self.film.bias)

    def forward(self, x: torch.Tensor, condition: torch.Tensor) -> torch.Tensor:
        s1, b1, s2, b2 = self.film(condition).unsqueeze(1).chunk(4, dim=-1)
        y = self.norm1(x) * (1 + s1) + b1
        x = x + self.attn(y, y, y, need_weights=False)[0]
        return x + self.mlp(self.norm2(x) * (1 + s2) + b2)


class WorldModelHead(nn.Module):
    def __init__(
        self,
        dim: int = 512,
        layers: int = 8,
        heads: int = 8,
        dynamics_layers: int = 4,
        past_frames: int = 16,
        horizon: int = 5,
        feature_dim: int = FEATURE_DIM,
        visual_dim: int = VISUAL_DIM,
    ):
        super().__init__()
        self.dim, self.past_frames, self.horizon = dim, past_frames, horizon
        # Dynamics: past hand states are read by one learned query per future step.
        self.state_proj = nn.Sequential(nn.LayerNorm(feature_dim), nn.Linear(feature_dim, dim))
        self.past_time = nn.Embedding(past_frames, dim)
        self.future_query = nn.Embedding(horizon, dim)
        decoder_layer = nn.TransformerDecoderLayer(dim, heads, 4 * dim, dropout=0.0, activation="gelu", batch_first=True, norm_first=True)
        self.dynamics = nn.TransformerDecoder(decoder_layer, dynamics_layers, norm=nn.LayerNorm(dim))
        self.visual_readout = nn.Linear(dim, visual_dim)
        # Touch: a rectified flow over 216 points. Offset 0 is the current frame, 1..horizon the future.
        self.x_proj = nn.Linear(2, dim)
        self.cond_proj = nn.Sequential(nn.LayerNorm(feature_dim), nn.Linear(feature_dim, dim))
        self.geom_proj = nn.Linear(3, dim)
        self.context_proj = nn.Linear(dim, dim)
        self.point_embed = nn.Embedding(NUM_POINTS, dim)
        self.offset_embed = nn.Embedding(horizon + 1, dim)
        self.time_mlp = nn.Sequential(nn.Linear(dim, dim), nn.GELU(), nn.Linear(dim, dim))
        self.blocks = nn.ModuleList(_Block(dim, heads) for _ in range(layers))
        self.out_norm = nn.LayerNorm(dim)
        self.out = nn.Linear(dim, 2)
        nn.init.zeros_(self.out.weight)
        nn.init.zeros_(self.out.bias)

    def imagine(self, past_cond: torch.Tensor) -> torch.Tensor:
        """past_cond [M, P, 216, C], one row per hand. Returns future latents [M, horizon, dim]."""
        batch, frames = past_cond.shape[:2]
        if frames > self.past_frames:
            raise ValueError(f"head was built for {self.past_frames} past frames, got {frames}")
        positions = torch.arange(frames, device=past_cond.device)
        memory = self.state_proj(past_cond).mean(2) + self.past_time(positions)
        return self.dynamics(self.future_query.weight.expand(batch, -1, -1), memory)

    def _time_embedding(self, t: torch.Tensor) -> torch.Tensor:
        half = self.dim // 2
        freqs = torch.exp(torch.arange(half, device=t.device, dtype=t.dtype) * (-math.log(10000.0) / max(half - 1, 1)))
        angles = t[:, None] * 1000.0 * freqs
        return self.time_mlp(torch.cat([angles.sin(), angles.cos()], dim=-1))

    def velocity(self, x, t, cond, offsets, step: torch.Tensor, context: torch.Tensor | None = None) -> torch.Tensor:
        # Offsets are in meters; dividing by a hand-sized length keeps them near unit scale.
        tokens = self.x_proj(x) + self.cond_proj(cond) + self.geom_proj(offsets / 0.1) + self.point_embed.weight
        if context is not None:
            tokens = tokens + self.context_proj(context)[:, None]
        condition = self._time_embedding(t) + self.offset_embed(step)
        for block in self.blocks:
            tokens = block(tokens, condition)
        return self.out(self.out_norm(tokens))

    def flow_matching_loss(self, cond, offsets, target, mask, step, context=None) -> torch.Tensor:
        """target [N, 216, 2], mask [N, 216] with True where the label exists."""
        noise = torch.randn_like(target)
        t = torch.rand(target.shape[0], device=target.device, dtype=target.dtype)
        x_t = (1 - t[:, None, None]) * noise + t[:, None, None] * target
        error = (self.velocity(x_t, t, cond, offsets, step, context) - (target - noise)) ** 2
        weight = mask.to(error.dtype)[..., None]
        return (error * weight).sum() / (weight.sum() * 2).clamp_min(1.0)

    @torch.no_grad()
    def sample(self, cond, offsets, step=None, context=None, num_samples: int = 8, steps: int = 10, seed: int = 0) -> torch.Tensor:
        """Euler integration of the flow. Returns [S, N, 216, 2]; seeded so evaluation repeats exactly."""
        generator = torch.Generator(device=cond.device).manual_seed(seed)
        count = cond.shape[0]
        step = torch.zeros(count, dtype=torch.long, device=cond.device) if step is None else step
        results = []
        for _ in range(num_samples):
            x = torch.randn(count, NUM_POINTS, 2, device=cond.device, dtype=cond.dtype, generator=generator)
            for index in range(steps):
                t = torch.full((count,), index / steps, device=cond.device, dtype=cond.dtype)
                x = x + self.velocity(x, t, cond, offsets, step, context) / steps
            results.append(x)
        return torch.stack(results)


def samples_to_outputs(samples: torch.Tensor) -> dict[str, torch.Tensor]:
    """Collapse samples into the fields the original head returns, so downstream code cannot tell."""
    probability = torch.sigmoid(PROBABILITY_SHARPNESS * samples[..., 0]).mean(0).clamp(1e-4, 1 - 1e-4)
    agreement = (2 * probability - 1).abs()
    return {
        "contact_probability": probability,
        "contact_logits": torch.logit(probability),
        "contact_log_distance": target_to_log_distance(samples[..., 1]).mean(0),
        # Log-confidence in the original head's [0, 2] range, from agreement between samples.
        "contact_log_conf": 2.0 * agreement,
    }


class WorldModelHooks:
    """Attach the head to a MarkerModel with PyTorch hooks. Inference outputs keep the official fields."""

    FIELDS = ("contact_probability", "contact_logits", "contact_log_distance", "contact_log_conf")

    def __init__(self, marker: nn.Module, head: WorldModelHead, options: dict | None = None):
        self.marker = marker
        self.head = head
        self.options = {"eval_samples": 8, "eval_steps": 10, "eval_seed": 0, **(options or {})}
        self.features: dict[str, torch.Tensor] = {}
        hand_head = marker.hand_head
        self._handles = [
            getattr(hand_head, f"{name}_output_norm").register_forward_hook(self._capture(name)) for name in ("root", "joint", "vertex")
        ]
        self._handles.append(hand_head.register_forward_hook(self._replace))

    def remove(self) -> None:
        for handle in self._handles:
            handle.remove()
        self._handles.clear()

    def _capture(self, name: str):
        def hook(_module, _inputs, output):
            self.features[name] = output

        return hook

    def conditioning(self) -> torch.Tensor:
        return torch.cat([self.features["root"][:, None], self.features["joint"], self.features["vertex"]], dim=1)

    def _replace(self, _module, _inputs, outputs):
        if self.marker.training:
            return outputs
        from .contact_confidence import contact_confidence_from_log

        offsets = torch.cat([outputs["joint_offset"], outputs["vertex_offset"]], dim=1)
        samples = self.head.sample(
            self.conditioning().float(),
            offsets.float(),
            num_samples=self.options["eval_samples"],
            steps=self.options["eval_steps"],
            seed=self.options["eval_seed"],
        )
        touch = samples_to_outputs(samples)
        replaced = dict(outputs)
        for prefix, points in (("joint", slice(0, 21)), ("vertex", slice(21, NUM_POINTS))):
            for field in self.FIELDS:
                key = f"{prefix}_{field}"
                replaced[key] = touch[field][:, points].to(dtype=outputs[key].dtype)
            replaced[f"{prefix}_contact_conf"] = contact_confidence_from_log(replaced[f"{prefix}_contact_log_conf"]).to(
                dtype=outputs[f"{prefix}_contact_conf"].dtype
            )
        return replaced


def attach_world_head(model: nn.Module, checkpoint_path) -> WorldModelHooks | None:
    """Install the head stored in a world checkpoint. An official checkpoint has none and runs unchanged."""
    payload = torch.load(checkpoint_path, map_location="cpu", weights_only=False)
    if "egotac_world_head" not in payload:
        return None
    options = payload["egotac_world_options"]
    head = WorldModelHead(options.get("dim", 512), options.get("layers", 8), options.get("heads", 8), options.get("dynamics_layers", 4), options["past_frames"], options["horizon"])
    head.load_state_dict(payload["egotac_world_head"])
    # Held by the hooks, not registered on the model: official code requires one dtype inside it.
    return WorldModelHooks(model, head.float().to(next(model.parameters()).device).eval(), options)
